"""Generate src/inspect_baxbench/scenarios.py from upstream BaxBench v1.0.0.

The Hugging Face dataset predates v1.0.0, which moved the Docker images from
Alpine to Debian (changing install commands) and reworded some API specs. This
reads each upstream scenario file with `ast` (nothing upstream is executed) and
writes the v1.0.0 scenario fields out as a Python module.

    uv run python scripts/generate_scenarios.py
"""

import ast
import pprint
from pathlib import Path
from typing import Any

ROOT = Path(__file__).parent.parent
SCENARIOS_DIR = ROOT / "reference" / "baxbench" / "src" / "scenarios"
OUTPUT = ROOT / "src" / "inspect_baxbench" / "scenarios.py"

FIELDS = [
    "short_app_description",
    "api_spec",
    "text_spec",
    "scenario_instructions",
    "needs_db",
    "needs_secret",
    "needed_packages",
]
DEFAULTS: dict[str, Any] = {"needed_packages": {}}

HEADER = '''"""BaxBench scenario fields, keyed by scenario ID.

`needed_packages` maps a language (or "_all_" for every language) to extra
install commands for the sandbox image.

Generated by scripts/generate_scenarios.py from BaxBench v1.0.0
(src/scenarios/*.py), MIT License, Copyright (c) 2025 SRI Lab, LogicStar.ai.
Do not edit by hand.
"""

from typing import Any

'''


def _evaluate(node: ast.expr, constants: dict[str, Any]) -> Any:
    """Evaluate a literal, a module-level constant, or an f-string of constants."""
    if isinstance(node, ast.Name):
        return constants[node.id]
    if isinstance(node, ast.JoinedStr):
        parts = []
        for value in node.values:
            if isinstance(value, ast.Constant):
                parts.append(value.value)
            elif (
                isinstance(value, ast.FormattedValue)
                and value.conversion == -1
                and value.format_spec is None
            ):
                parts.append(str(_evaluate(value.value, constants)))
            else:
                raise ValueError(f"Unsupported f-string part: {ast.dump(value)}")
        return "".join(parts)
    return ast.literal_eval(node)


def read_scenario(path: Path) -> tuple[str, dict[str, Any]]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    constants = {}
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
        ):
            try:
                constants[node.targets[0].id] = ast.literal_eval(node.value)
            except ValueError:
                pass  # not a literal, e.g. a function call
    call = next(
        node
        for node in ast.walk(tree)
        if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "Scenario"
    )
    kwargs = {kw.arg: kw.value for kw in call.keywords}
    scenario_id = _evaluate(kwargs["id"], constants)
    fields = {
        field: _evaluate(kwargs[field], constants) if field in kwargs else DEFAULTS[field]
        for field in FIELDS
    }
    return scenario_id, fields


def main() -> None:
    scenarios = dict(
        sorted(
            read_scenario(path)
            for path in SCENARIOS_DIR.glob("*.py")
            if path.name not in ("__init__.py", "base.py")
        )
    )
    body = "SCENARIOS: dict[str, dict[str, Any]] = " + pprint.pformat(
        scenarios, width=88, sort_dicts=False
    )
    OUTPUT.write_text(HEADER + body + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(scenarios)} scenarios to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
